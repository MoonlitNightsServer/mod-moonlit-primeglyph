#!/usr/bin/env python3
"""Prime Inscription (spell 5,800,010): the cast of the virtual Prime glyph socket.

Writes data/sql/db-world/zz_moonlit_primeglyph_10_spell_dbc.sql: ONE full spell_dbc overlay row (client and server both read it),
cloned from stock spell 56182 (Glyph of Smite's use spell) with the same pattern as tools/talents/spellkit.py make():
  * Blizzard's own cast settings are kept: a glyph cast time (CastingTimeIndex 6), "not in combat" (Attributes 0x10000000),
    interrupted by movement and damage (InterruptFlags 63) and the inscription visual (12369);
  * Targets 0 (not a glyph-slot cast), effect 1 = DUMMY on the caster (effects 2 and 3 cleared), SpellClassSet 0 (no class
    family modifier can touch it), name and description replaced. The server inscribes in an ALE hook when the cast completes.
Gen-1 spell 110030 -> 5,800,010 (Registry section 8, glyph system block 5,800,000).

Run:  python -I tools/gen_prime_inscription.py < /dev/null      (database up; READ-ONLY: the live overlay is read through
                                                                  tools/phase2/effective.py, nothing is written to a database)
Then the client patch needs this Phase 2 manifest line (docs/Ruling_Phase2_Manifest.csv, header dbc,gen1_id,kind,owner,phase,gen2_id,note):
  Spell,5800010,new,ours,4,5800010,custom: prime glyph (Prime Inscription)
and the module SQL must be applied to the live database BEFORE the client patch is built (the builder reads the live overlay).
~Moonlit Nights Team
"""
import sys
from pathlib import Path

ROOT = next(p for p in Path(__file__).resolve().parents if (p / "tools" / "mn.py").exists())
MODULE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools" / "talents"))      # spellkit pulls in tools/phase2 itself
import spellkit as k  # noqa: E402
import gen_sql as gs  # noqa: E402

NEW_ID, DONOR = 5800010, 56182
NAME = "Prime Inscription"
DESC = "Inscribes a glyph into your Prime glyph socket."
OUT = MODULE / "data" / "sql" / "db-world" / "zz_moonlit_primeglyph_10_spell_dbc.sql"

row = k.make(NEW_ID, DONOR, (NAME, DESC, ""), SpellClassSet=0, Targets=0)
k.effects(row, dict(effect=k.EFF.DUMMY, target=1))       # also clears effects 2 and 3 and the donor's glyph id in MiscValue

# Blizzard's cast settings must have survived the clone, or the cast is no longer a glyph cast: stop and look.
ix = k.IDX
checks = {"Attributes": 0x10000000, "CastingTimeIndex": 6, "InterruptFlags": 63, "SpellVisualID_1": 12369, "Targets": 0, "Effect_1": k.EFF.DUMMY,
          "Effect_2": 0, "Effect_3": 0, "SpellClassSet": 0}
for col, want in checks.items():
    got = row[ix[col]]
    assert got == want, f"{col}: expected {want}, got {got} (donor changed?)"
assert row[0] == NEW_ID and all(ord(c) < 128 for c in NAME + DESC)
assert NEW_ID not in k.g2.ids("Spell"), f"spell {NEW_ID} already exists in the binary DBC or the live overlay"

cols = ", ".join(f"`{c[0]}`" for c in k.COLS)
vals = ", ".join(gs.q(v, k.COLS[i][1]) for i, v in enumerate(row))
sql = ("-- Moonlit Prime Glyph: Prime Inscription, the cast of the Prime glyph socket. Generated by tools/gen_prime_inscription.py; do not edit by hand.\n"
       "-- A full overlay row cloned from stock spell 56182. Idempotent (delete by exact ID, then insert). ~Moonlit Nights Team\n"
       f"DELETE FROM `spell_dbc` WHERE `ID` = {NEW_ID};\n"
       f"INSERT INTO `spell_dbc` ({cols}) VALUES\n({vals});\n")
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(sql, encoding="utf-8", newline="\n")
print(f"wrote {OUT} ({len(row)} columns)")
print(f"manifest line: Spell,{NEW_ID},new,ours,4,{NEW_ID},custom: prime glyph (Prime Inscription)")
