#!/usr/bin/env python3
"""Prime glyph data: glyph item -> glyph table, generated from the facts gen 2 still has.

Writes <repo>/lua_scripts/primeglyph/primeglyph_data.lua (the authoritative Lua copy; this module folder keeps SQL and docs only):

  PRIME_GLYPHS[itemEntry] = { glyph = GlyphProperties.ID, spell = the glyph's passive aura, use = the item's own use spell,
                              icon = SpellIcon path of the rune, class = class id, minor = true|nil, prime = true|nil, name = "..." }
  PRIME_GLYPH_ITEMS   = { item, ... }        the Prime-type glyphs (GlyphProperties TypeFlags 2): none in gen 2 yet
  PRIME_GLYPH_BY_USE[useSpell] = item        for the right-click -> click-the-socket flow

How the facts chain together (all read-only):
  item_template (live world DB, class 16 = glyph, subclass = class id, spellid_1 = the use spell)
    -> Spell (binary data/dbc/Spell.dbc, overridden by the live spell_dbc overlay, via tools/phase2/effective.py):
       the use spell has SPELL_EFFECT_APPLY_GLYPH (74) and EffectMiscValue = the GlyphProperties id
    -> GlyphProperties.dbc (data/dbc; the glyphproperties_dbc overlay table is empty in gen 2):
       field 1 = the passive aura, field 2 = TypeFlags (0 Major, 1 Minor, 2 Prime), field 3 = SpellIcon id
    -> SpellIcon.dbc: the rune texture path.

Classes listed in EXCLUDED_CLASSES are left out: Paladin (2), Hunter (3), Shaman (7), Priest (5) and Mage (8) use Moonlit Blessings Favors instead of a Prime glyph.
When another class gets Blessings, add it to the list here AND to the same list in lua_scripts/primeglyph/primeglyph_core.lua and
client-addon/MoonlitPrimeGlyph/MoonlitPrimeGlyph.lua.

Run: python -I tools/build_primeglyph_data.py < /dev/null        (database up, SELECT only)
~Moonlit Nights Team
"""
import sys
from pathlib import Path

ROOT = next(p for p in Path(__file__).resolve().parents if (p / "tools" / "mn.py").exists())
sys.path.insert(0, str(ROOT / "tools" / "phase2"))
import effective as ef  # noqa: E402

EXCLUDED_CLASSES = {}        # 2026-10-26: Blessings are off, every class gets the Prime socket (put a class back here when it uses Blessings Favors)
APPLY_GLYPH = 74
OUT = ROOT / "lua_scripts" / "primeglyph" / "primeglyph_data.lua"


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    g2 = ef.gen2()
    cols = [c[0] for c in g2.cols("Spell")]
    ix = {n: i for i, n in enumerate(cols)}
    gp, gp_strs, _ = ef.read_dbc(ef.GEN2_DBC / "GlyphProperties.dbc")
    si, si_strs, _ = ef.read_dbc(ef.GEN2_DBC / "SpellIcon.dbc")
    for r in ef.sql("SELECT ID, SpellID, GlyphSlotFlags, SpellIconID FROM glyphproperties_dbc", ef.GEN2_DB):      # overlay rows win over the binary
        gp[int(r[0])] = tuple(int(v) for v in r)

    items = ef.sql("SELECT entry, name, subclass, spellid_1 FROM item_template WHERE class = 16 ORDER BY entry", ef.GEN2_DB)
    out, no_spell, no_glyph, excluded = [], [], [], []
    for entry, name, subclass, use in items:
        entry, subclass, use = int(entry), int(subclass), int(use)
        row = g2.row("Spell", use) if use else None
        gid = None
        if row:
            for k in (1, 2, 3):
                if row[ix[f"Effect_{k}"]] == APPLY_GLYPH:
                    gid = row[ix[f"EffectMiscValue_{k}"]]
        if gid is None:
            no_spell.append(entry)
            continue
        if gid not in gp or gp[gid][1] == 0:
            no_glyph.append(entry)
            continue
        if subclass in EXCLUDED_CLASSES:
            excluded.append(entry)
            continue
        icon = ef._text(si_strs, si[gp[gid][3]][1]) if gp[gid][3] in si else ""
        out.append((entry, gid, gp[gid][1], subclass, gp[gid][2], name, use, icon))
    # gen 2: every class is a Blessings class, so no Prime glyph is left (the data file is then empty)

    lines = [
        "-- GENERATED by core/modules/mod-moonlit-primeglyph/tools/build_primeglyph_data.py -- do not hand-edit. ~Moonlit Nights Team",
        f"-- item entry -> glyph. {len(out)} glyph items. Left out: {len(excluded)} Shaman/Priest glyphs (they use Blessings Favors), "
        f"{len(no_spell) + len(no_glyph)} item rows that are not real glyphs (no inscription use spell or no GlyphProperties row).",
        "PRIME_GLYPHS = {",
    ]
    for e, g, spell, cls, gtype, name, use, icon in sorted(out):
        kind = {1: ", minor = true", 2: ", prime = true"}.get(gtype, "")
        lines.append(f"  [{e}] = {{ glyph = {g}, spell = {spell}, use = {use}, class = {cls}{kind}, icon = {lua_str(icon)}, name = {lua_str(name)} }},")
    lines += [
        "}",
        "PRIME_GLYPH_ITEMS = { %s }" % ", ".join(str(o[0]) for o in sorted(out) if o[4] == 2),
        "PRIME_GLYPH_BY_USE = {}",
        "for item, g in pairs(PRIME_GLYPHS) do PRIME_GLYPH_BY_USE[g.use] = item end",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    types = {t: sum(1 for o in out if o[4] == t) for t in (0, 1, 2)}
    uses = [o[6] for o in out]
    assert len(set(uses)) == len(uses), "two glyph items share a use spell"
    print(f"{OUT}: {len(out)} glyphs (major {types[0]}, minor {types[1]}, prime-type {types[2]}); "
          f"excluded Shaman/Priest {len(excluded)}; not real glyphs {len(no_spell) + len(no_glyph)}: {no_spell + no_glyph}")


if __name__ == "__main__":
    main()
